// Writes tests/fixtures/cues.json and tests/android/Expected.kt: expected plans from the TypeScript, for the native checks.
import { readFileSync, writeFileSync } from "node:fs";
import { eventPlan, isMuted, rawResourceName, validateManifest } from "../implementation/web/cue-model.ts";

const manifest = JSON.parse(readFileSync(new URL("fixtures/sounds.json", import.meta.url), "utf8"));
const NAMES = [...Object.keys(manifest.events), "tap", "flip", "nothing"];
const FILES = ["tap.wav", "ui/Bot-Add.wav", "deal 2.mp3", "Win!.ogg"];

export function build(): string {
  return JSON.stringify({
    plans: NAMES.map((event) => ({ event, steps: eventPlan(manifest, event) })),
    resources: FILES.map((file) => ({ file, name: rawResourceName(file) })),
    muted: [[true, true], [true, false], [false, true], [false, false], [null, true], [null, false]].map(([sound, def]) => ({ sound, defaultMuted: def, muted: isMuted(sound as boolean | null, def as boolean) })),
    problems: validateManifest(manifest),
  }, null, 1) + "\n";
}

// The plans as Kotlin source rows, so the Android check needs no JSON library.
export function buildKotlin(): string {
  const d = JSON.parse(build());
  const plans = d.plans.map((p: any) => `    arrayOf("${p.event}", "${p.steps.map((s: any) => `${s.cue}:${s.delayMs}`).join(" ")}"),`);
  const res = d.resources.map((r: any) => `    arrayOf("${r.file}", "${r.name}"),`);
  return `// Generated by tests/make-fixtures.ts from the TypeScript cue model and tests/fixtures/sounds.json.
// event, "cue:delayMs ..." as planned
val EXPECTED_PLANS = listOf(
${plans.join("\n")}
)
// file, Android raw resource name
val EXPECTED_RESOURCES = listOf(
${res.join("\n")}
)
`;
}

if (import.meta.main) {
  writeFileSync(new URL("fixtures/cues.json", import.meta.url), build());
  writeFileSync(new URL("android/Expected.kt", import.meta.url), buildKotlin());
}
